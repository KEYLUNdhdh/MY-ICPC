constexpr i64 MOD = 998244353, INF = 1e9;


i64 qpow(i64 a, i64 b)
{
    i64 res = 1;
    while(b)
    {
        if(b & 1)
            res = res * a % MOD;
        a = a * a % MOD;
        b >>= 1;
    }
    return res;
}

void solve()
{
    i64 n, m, r, c;
    cin >> n >> m >> r >> c;

    i64 up = (r * c - 1) % (MOD - 1) + (n - r) * (c - 1) % (MOD - 1) + (m - c) * (r - 1) % (MOD - 1);
    up = (up + MOD - 1) % (MOD - 1);
    cout << qpow(2, up) << "\n";
}

